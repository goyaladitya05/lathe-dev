# Public export of lathe: main's tracked files at REV, without the private dev notes.
#   python3 release/export.py REV OUT_DIR
# src/chisel/ -> src/sass/ (identifiers sass_*), provenance notes and local-doc references dropped, README and LICENSE
# from release/. Fails if a private reference survives anywhere in the text.
import io
import re
import subprocess
import sys
import tarfile
from pathlib import Path

REV, OUT = sys.argv[1], Path(sys.argv[2])
HERE = Path(__file__).resolve().parent
SKIP = {"README.md"}  # and everything under release/ (private release tooling)

EXACT = [  # (old, new), each must occur in the export at least once
    ("# ADAM8=1 -> build/..._adam8: 8-bit AdamW moments for the layer matrices (BENCH.md)",
     "# ADAM8=1 -> build/..._adam8: 8-bit AdamW moments for the layer matrices"),
    ("layer weight grads by cuBLASLt instead of own / chisel kernels", "layer weight grads by cuBLASLt instead of own / SASS kernels"),
    ("# chisel's SASS dW cores for this model and token count, when built (src/chisel/, from chisel's gen/lathe_export.py); sm_89 only",
     "# prebuilt SASS dW cores for this model and token count, when there are any (src/sass/); sm_89 only"),
    ("Prints BENCH.md rows", "Prints markdown table rows"),
    (" (BENCH.md): rerun once", ": rerun once"),
    (" (tinygrad's NV backend fails BEAM here, see BENCH.md)", " (tinygrad's NV backend fails BEAM here)"),
    ("CUDA graph capture (BENCH.md)", "CUDA graph capture"),
    (" (format in BENCH.md \"8-bit AdamW state\")", ""),
    ("Precision follows PyTorch bf16 autocast (BENCH.md).", "Precision follows PyTorch bf16 autocast."),
    ("swept on sm89 (BENCH.md profiles)", "swept on sm89"),
    ("// chisel was built for run its hand-scheduled SASS core instead (src/chisel/, same bits: chisel e037).",
     "// with a prebuilt core run hand-scheduled SASS instead (src/sass/, same bits)."),
    ("(make ADAM8=1; format in BENCH.md \"8-bit AdamW state\")", "(make ADAM8=1)"),
    ("Tuned at 1x704 (chisel e054: 14 blocks", "Tuned at 1x704 (14 blocks"),
    ("(chisel e066, 8-bit at 1xT)", "(8-bit at 1xT)"),
    ("instead of chisel's / dw_bf16", "instead of the SASS cores / dw_bf16"),
    ("(adamw_stream8, BENCH.md)", "(adamw_stream8)"),
    ("// Layer dW cores in hand-scheduled SASS from chisel (github goyaladitya05/chisel, gen/lathe_export.py): one header",
     "// Layer dW cores in prebuilt hand-scheduled SASS (src/sass/): one header"),
    ("the bits are the same either way (chisel e037).", "the bits are the same either way."),
    ("\"chisel header built for another shape\"", "\"SASS header built for another shape\""),
    ("dw_bf16 / chisel's, head_dw_adamw", "dw_bf16 / SASS, head_dw_adamw"),
    ("the memory-bound kernels\n// after it: chisel e048-e051, e054), and", "the memory-bound kernels\n// after it), and"),
    ("BENCH.md\nproject.md\n", ""),
]
REGEX = [  # generic rewrites after EXACT
    (r" \(chisel e\d+(?:[-,] ?e\d+)*\)", ""),
    (r"CHISEL_DW_H", "SASS_DW_H"), (r"HAVE_CHISEL_DW", "HAVE_SASS_DW"), (r"chisel_dw", "sass_dw"), (r"chisel/dw_", "sass/dw_"),
    (r"\[\"flock\", \"/tmp/gpu-bench.lock\",  # shared GPU: each probe holds the lock\n\s*sys.executable", "[sys.executable"),
    (r"^// Generated by chisel [^\n]*\n// Hand-scheduled sm_89 SASS, assembled and hazard-checked by chisel. Do not edit.",
     "// Prebuilt cubins: hand-scheduled sm_89 SASS for the four layer dW GEMMs at this token count. Do not edit."),
]
FORBID = re.compile(r"(?i:chisel|project\.md|gpu-bench|lathe-(?:4c|e0|52|at|fp8|dev)|/home/)|BENCH")

tar = tarfile.open(fileobj=io.BytesIO(subprocess.run(["git", "-C", str(HERE.parent), "archive", REV], check=True,
                                                     capture_output=True).stdout))
files = {}
for m in tar.getmembers():
    if m.isfile() and m.name not in SKIP and not m.name.startswith("release/"):
        files[m.name.replace("src/chisel/", "src/sass/")] = (tar.extractfile(m).read().decode(), m.mode)
used = {old: 0 for old, _ in EXACT}
for name, (text, mode) in files.items():
    for old, new in EXACT:
        used[old] += text.count(old)
        text = text.replace(old, new)
    for pat, new in REGEX:
        text = re.sub(pat, new, text, flags=re.M)
    files[name] = (text, mode)
files["README.md"] = ((HERE / "README.md").read_text(), 0o644)
files["LICENSE"] = ((HERE / "LICENSE").read_text(), 0o644)
missing = [old for old, n in used.items() if not n]
bad = [(n, i + 1, l.strip()[:100]) for n, (t, _) in files.items() for i, l in enumerate(t.splitlines()) if FORBID.search(l)]
if missing or bad:
    sys.exit("export.py: unused rewrites " + repr(missing) + "\nprivate references left:\n" + "\n".join(map(str, bad)))
for name, (text, mode) in files.items():
    p = OUT / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    p.chmod(mode)
print(f"exported {len(files)} files from {REV} to {OUT}")
